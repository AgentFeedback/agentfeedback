func TestRegistry_Complete(t *testing.T) {
	e := testEnv(t)
	date := regexp.MustCompile(`^\d{4}-\d{2}-\d{2}$`)
	seen := map[string]bool{}
	for _, a := range Adapters() {
		if a.Name == "" || seen[a.Name] {
			t.Fatalf("empty or repeated name %q", a.Name)
		}
		seen[a.Name] = true
		bad := func(what string) { t.Errorf("%s: %s", a.Name, what) }
		if len(a.Binaries) == 0 && len(a.ConfigDirs(e)) == 0 {
			bad("no binary and no config directory")
		}
		if len(a.SkillDirs(e)) == 0 && a.NoSkill == "" {
			bad("no skill directory and no reason")
		}
		if (a.Instructions.Global == nil || len(a.Instructions.Global(e)) == 0) && a.Instructions.NoGlobal == "" {
			bad("no global instruction file and no reason")
		}
		if len(a.Instructions.Project) == 0 {
			bad("no project instruction file")
		}
		switch {
		case a.Hook.Format == "":
			bad("no hook format")
		case a.Hook.Format == "none" && a.Hook.NoHook == "":
			bad("hook none without a reason")
		case a.Hook.Format != "none" && a.Hook.File == nil:
			bad("hook without a file")
		}
		for _, k := range []string{EventToolFailed, EventTurnEnd, EventSessionStart} {
			if a.Hook.Events[k] == "" {
				bad("event " + k + " missing")
			}
		}
		if a.MCP.URLShape == "" && a.MCP.NoMCP == "" {
			bad("no MCP entry and no reason")
		}
		if a.Sessions.Reader == "" || (a.Sessions.Reader == "none" && a.Sessions.NoReader == "") {
			bad("no session reader and no reason")
		}
		if !slices.Contains([]string{LevelDocumented, LevelFixtureTested, LevelLiveChecked}, a.Verified.Level) || !date.MatchString(a.Verified.Date) {
			bad("verification " + a.Verified.Level + " " + a.Verified.Date)
		}
		// Every mode is either wired or refused with a next step.
		for _, mode := range []string{ModeCLI, ModeMCP} {
			ok, reason := Supports(a.Name, mode)
			if !ok && reason == "" {
				bad(mode + " refused without a reason")
			}
		}
	}
	if !slices.Equal(Names(), names) || len(names) != len(seen) {
		t.Errorf("names %v", Names())
	}
}

func TestDocsHarnessTable(t *testing.T) {
	const begin = "<!-- harness-table:begin: generated by go test ./internal/harness -run TestDocsHarnessTable -update -->\n"
	const end = "<!-- harness-table:end -->"
	path := filepath.Join("..", "..", "docs", "operate.md")
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	doc := string(data)
	i, j := strings.Index(doc, begin), strings.Index(doc, end)
	if i < 0 || j < i {
		t.Fatalf("%s has no harness-table block", path)
	}
	got, want := doc[i+len(begin):j], DocsTable()
	if got == want {
		return
	}
	if !*update {
		t.Fatalf("the harness table in %s is not the registry's; run go test ./internal/harness -run TestDocsHarnessTable -update\ngot:\n%s\nwant:\n%s", path, got, want)
	}
	if err := os.WriteFile(path, []byte(doc[:i+len(begin)]+want+doc[j:]), 0o644); err != nil {
		t.Fatal(err)
	}
}

func TestVSCodeUserDir(t *testing.T) {
	e := testEnv(t)
	orig := goos
	t.Cleanup(func() { goos = orig })
	goos = "linux"
	if got := e.vscodeUserDir(); got != filepath.Join(e.Home, ".config", "Code", "User") {
		t.Errorf("linux: %s", got)
	}
	goos = "darwin"
	if got := e.vscodeUserDir(); got != filepath.Join(e.Home, "Library", "Application Support", "Code", "User") {
		t.Errorf("darwin: %s", got)
	}
	goos = "windows"
	if got := e.vscodeUserDir(); got != filepath.Join(e.Home, "AppData", "Roaming", "Code", "User") {
		t.Errorf("windows without APPDATA: %s", got)
	}
	appdata := filepath.Join(e.Home, "roaming")
	e.Getenv = func(k string) string {
		if k == "APPDATA" {
			return appdata
		}

		return ""
	}
	if got := e.vscodeUserDir(); got != filepath.Join(appdata, "Code", "User") {
		t.Errorf("windows with APPDATA: %s", got)
	}
}

