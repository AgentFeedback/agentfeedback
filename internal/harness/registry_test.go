func TestInstall_RefusedModes(t *testing.T) {
	e := testEnv(t)
	for _, tt := range []struct{ name, mode, problem string }{
		{"vscode", ModeCLI, "vscode has no skill directory of its own; VS Code reads the skill that the copilot or claude-code adapter installs"},
		{"gemini-cli", ModeMCP, "gemini-cli has no MCP entry in agentfeedback install"},
	} {
		req := cliRequest(tt.name)
		req.Options.Mode = tt.mode
		_, err := e.Run(req)
		r, ok := err.(*Refusal)
		if !ok || r.Problem != tt.problem {
			t.Errorf("%s/%s: %v", tt.name, tt.mode, err)
		}
	}
	if _, err := os.Stat(e.ManifestPath()); err == nil {
		t.Error("a manifest was written")
	}
}

// display is path in the form the docs table writes it.
func display(e Env, a Adapter, path string) string {
	type sub struct{ prefix, with string }
	subs := []sub{
		{e.claudeDir(), "<claude config>"}, {e.codexHome(), "<codex home>"}, {e.opencodeDir(), "<opencode>"},
		{e.vscodeUserDir(), "<Code/User>"}, {e.Home, "~"},
	}
	if a.Name == "amp" {
		subs = append(subs, sub{e.xdgConfig(), "<xdg>"})
	}
	slices.SortStableFunc(subs, func(x, y sub) int { return len(y.prefix) - len(x.prefix) })
	for _, s := range subs {
		if rest, ok := strings.CutPrefix(path, s.prefix); ok && (rest == "" || strings.HasPrefix(rest, "/")) {
			return s.with + rest
		}
	}

	return path
}

func TestRegistry_AgreesWithWiring(t *testing.T) {
	orig := goos
	t.Cleanup(func() { goos = orig })
	goos = "linux"
	e := testEnv(t)
	withDocs(t, map[string]string{"SKILL.md": "v1\n"})
	for _, a := range Adapters() {
		config, owned := registry[slices.IndexFunc(registry, func(r Adapter) bool { return r.Name == a.Name })].files(e)
		known := append(slices.Clone(config), owned...)
		hookFile := ""
		if a.Hook.File != nil {
			hookFile = a.Hook.File(e)
		}
		if (hookFile != "") != (a.Hook.Format != "none") {
			t.Errorf("%s: hook file %q with format %s", a.Name, hookFile, a.Hook.Format)
		}
		mcpFile := ""
		if a.MCP.File != nil {
			mcpFile = a.MCP.File(e)
		}
		for _, mode := range []string{ModeCLI, ModeMCP} {
			if ok, _ := Supports(a.Name, mode); !ok {
				continue
			}
			p := newPlan(e, newManifest())
			d, err := p.desired(a.Name, Options{Mode: mode, Reminder: true, Docs: true, Server: "https://x.test", Binary: "/bin/af"})
			if err != nil {
				t.Fatalf("%s/%s: %v", a.Name, mode, err)
			}
			sawHook := false
			for _, it := range d.items {
				if it.Kind == KindClaudeMCP {
					continue
				}
				bad := func(why string) { t.Errorf("%s/%s: %s %s: %s", a.Name, mode, it.Role, it.File, why) }
				switch it.Role {
				case RoleSkill, RoleDocs:
					if !slices.ContainsFunc(a.SkillDirs(e), func(d string) bool { return strings.HasPrefix(it.File, d+"/") }) {
						bad("not under a skill directory")
					}

					continue
				case RoleHook, RoleReminder:
					sawHook = true
					if it.File != hookFile {
						bad("not Hook.File " + hookFile)
					}
				case RoleMCP:
					if it.File != mcpFile && !slices.Contains(config, it.File) {
						bad("not MCP.File " + mcpFile)
					}
				}
				if !slices.Contains(known, it.File) {
					bad("not in files()")
				}
			}
			if mode == ModeCLI && sawHook != (a.Hook.Format != "none") {
				t.Errorf("%s: hook items %v with format %s", a.Name, sawHook, a.Hook.Format)
			}
		}
		// The docs row names the declared paths.
		r := registry[slices.IndexFunc(registry, func(r Adapter) bool { return r.Name == a.Name })].row
		for _, d := range a.SkillDirs(e) {
			if want := display(e, a, filepath.Join(d, "agentfeedback", "SKILL.md")); !strings.Contains(r.skill, want) {
				t.Errorf("%s: skill cell %q lacks %s", a.Name, r.skill, want)
			}
		}
		if a.Hook.Format != "none" {
			if want := display(e, a, hookFile); !strings.Contains(r.hook, want) {
				t.Errorf("%s: hook cell %q lacks %s", a.Name, r.hook, want)
			}
		}
		if mcpFile != "" && a.Name != "claude-code" {
			want := display(e, a, mcpFile)
			if a.Name == "opencode" || a.Name == "amp" {
				want = filepath.Base(mcpFile)
			}
			if !strings.Contains(r.mcp, want) {
				t.Errorf("%s: mcp cell %q lacks %s", a.Name, r.mcp, want)
			}
		}
	}
	var rows []string
	for _, line := range strings.Split(strings.TrimSpace(DocsTable()), "\n")[2:] {
		name, _, _ := strings.Cut(strings.TrimPrefix(line, "| `"), "`")
		rows = append(rows, name)
	}
	if !slices.Equal(rows, Names()) {
		t.Errorf("table rows %v", rows)
	}
}
